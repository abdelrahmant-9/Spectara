/**
 * Polar's native license_key feature emits this when a license is granted
 * (after order checkout completes). This is the primary code path —
 * customers paste the Polar-issued key into the extension.
 */
async function upsertFromLicenseKey(env, lk) {
  const key = String(lk.key || "").trim().toUpperCase();
  if (!key) return;
  const email = String(lk?.customer?.email || lk?.user?.email || "").toLowerCase();
  const polarLicenseId = String(lk.id || "");
  const status = (lk.status === "granted" || lk.status === "active") ? "active" : "cancelled";

  // Expiry: license_keys can be tied to a subscription. Polar doesn't always
  // send expires_at on license_key.created — subscription.updated webhook
  // fills it in. Default to NULL (treat as active until subscription says
  // otherwise).
  const expires_at = lk.expires_at ? Date.parse(lk.expires_at) : null;
  const now = Date.now();
  const tier = inferTier(lk);

  const existing = await env.DB.prepare(
    "SELECT key FROM licenses WHERE polar_license_key_id = ? OR key = ?"
  ).bind(polarLicenseId, key).first();

  if (existing) {
    await env.DB.prepare(
      `UPDATE licenses
         SET key = ?, email = COALESCE(?, email), tier = ?, status = ?,
             expires_at = COALESCE(?, expires_at), updated_at = ?,
             polar_license_key_id = ?
       WHERE key = ?`
    ).bind(key, email || null, tier, status, expires_at, now, polarLicenseId, existing.key).run();
  } else {
    await env.DB.prepare(
      `INSERT INTO licenses
         (key, email, tier, status, expires_at, created_at, updated_at,
          polar_license_key_id)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?)`
    ).bind(key, email, tier, status, expires_at, now, now, polarLicenseId).run();
  }
}

/**
 * Order.created fires before license_key.created. We use it to record
 * polar_order_id linkage in case the license_key event arrives later or
 * is replayed. License row is created/updated when license_key fires.
 */
async function upsertFromOrder(env, order) {
  // For products without license_keys enabled, generate our own SL- key
  // and treat order as a lifetime purchase. With license_keys enabled
  // (recommended), this is a no-op — license_key.created handles it.
  const hasLicenseFeature = !!(order.product?.has_license_key || order.product?.benefits?.some?.((b) => b.type === "license_keys"));
  if (hasLicenseFeature) return;

  const email = String(order?.customer?.email || "").toLowerCase();
  const orderId = String(order.id || "");
  const tier = inferTier(order);
  if (!ALLOWED_TIERS.has(tier)) return;

  const existing = await env.DB.prepare(
    "SELECT key FROM licenses WHERE polar_order_id = ?"
  ).bind(orderId).first();
  if (existing) return;

  const key = generateLicenseKey();
  const now = Date.now();
  await env.DB.prepare(
    `INSERT INTO licenses
       (key, email, tier, status, expires_at, created_at, updated_at, polar_order_id)
     VALUES (?, ?, ?, 'active', NULL, ?, ?, ?)`
  ).bind(key, email, tier, now, now, orderId).run();
}

async function upsertFromSubscription(env, sub) {
  const subId = String(sub.id || "");
  const email = String(sub?.customer?.email || sub?.user?.email || "").toLowerCase();
  const tier = inferTier(sub);
  if (!ALLOWED_TIERS.has(tier)) return;

  // Polar typically sends current_period_end (ISO string) or ends_at on cancel.
  const endsAtStr = sub.current_period_end || sub.ends_at || null;
  const expires_at = endsAtStr ? Date.parse(endsAtStr) : null;
  const now = Date.now();

  await env.DB.prepare(
    `UPDATE licenses
       SET status = 'active', tier = ?, expires_at = ?, updated_at = ?,
           polar_subscription_id = ?
     WHERE polar_subscription_id = ?
        OR polar_order_id = ?`
  ).bind(tier, expires_at, now, subId, subId, sub.order_id || "").run();

  // If no row matched (subscription created without prior license), create one
  const existing = await env.DB.prepare(
    "SELECT key FROM licenses WHERE polar_subscription_id = ?"
  ).bind(subId).first();
  if (!existing) {
    const key = generateLicenseKey();
    await env.DB.prepare(
      `INSERT INTO licenses
         (key, email, tier, status, expires_at, created_at, updated_at, polar_subscription_id)
       VALUES (?, ?, ?, 'active', ?, ?, ?, ?)`
    ).bind(key, email, tier, expires_at, now, now, subId).run();
  }
}

async function markCancelledFromSubscription(env, sub) {
  const subId = String(sub.id || "");
  const now = Date.now();
  await env.DB.prepare(
    "UPDATE licenses SET status = 'cancelled', updated_at = ? WHERE polar_subscription_id = ?"
  ).bind(now, subId).run();
}

/* ------------------------------------------------------------------ */
/*  Tier inference                                                      */
/*  Polar attaches metadata to product / variant. Set                   */
/*    metadata: { tier: "pro" }                                         */
/*  on each variant in Polar dashboard for explicit control.            */
/* ------------------------------------------------------------------ */
function inferTier(obj) {
  const explicit = obj?.metadata?.tier
    || obj?.product?.metadata?.tier
    || obj?.subscription?.metadata?.tier;
  if (explicit && ALLOWED_TIERS.has(explicit)) return explicit;

  const name = String(
    obj?.product?.name
    || obj?.product_name
    || obj?.subscription?.product?.name
    || ""
  ).toLowerCase();
  if (name.includes("enterprise")) return "enterprise";
  if (name.includes("team")) return "team";
  return "pro";
}

/* ------------------------------------------------------------------ */
/*  Fallback SL- key generator (when Polar license keys are NOT used)   */
/* ------------------------------------------------------------------ */
const KEY_ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789";
function generateLicenseKey() {
  const block = () => {
    const buf = crypto.getRandomValues(new Uint8Array(4));
    return Array.from(buf, (b) => KEY_ALPHABET[b % KEY_ALPHABET.length]).join("");
  };
  return `SL-${block()}-${block()}-${block()}`;
}
